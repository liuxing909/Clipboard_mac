import Foundation
import CryptoKit
import Darwin

public enum ClipKind: String, Codable, Sendable {
    case text, image, richText, files
}

public struct ClipEntry: Codable, Identifiable, Equatable, Sendable {
    public let id: UUID
    public let digest: String
    public let kind: ClipKind
    public let text: String?
    public let imageFilename: String?
    public let imageWidth: Int?
    public let imageHeight: Int?
    public let richTextFilename: String?
    public let richTextTypes: [String]?
    public let fileURLs: [String]?
    public let byteCount: Int
    public let createdAt: Date
    public var copiedAt: Date
    public var sourceApp: String
    public var isPinned: Bool
    public var copyCount: Int

    public var title: String {
        switch kind {
        case .image: return "图片 · \(imageWidth ?? 0) × \(imageHeight ?? 0)"
        case .richText: return text?.isEmpty == false ? text! : "富文本内容"
        case .files:
            return text ?? fileURLs?.compactMap { URL(string: $0)?.lastPathComponent }.joined(separator: "\n") ?? "文件"
        case .text: return text ?? ""
        }
    }
}

public enum ClipPayload: Sendable {
    case text(String)
    case image(png: Data, width: Int, height: Int)
    case richText(text: String, formats: [String: Data])
    case files([URL])
}

public enum HistoryError: LocalizedError {
    case tooLarge, emptyContent, tooManyPins, unsupportedVersion, invalidImage, invalidFormats, invalidFileReferences,
        damagedHistory, capacityExceeded, manifestTooLarge, excludedContent
    public var errorDescription: String? {
        switch self {
        case .tooLarge: return "内容超过大小限制：文字 1 MiB、富文本 4 MiB、图片 20 MiB，文件引用最多 100 个、1 MiB。"
        case .emptyContent: return "剪贴板里没有可保存的内容。"
        case .tooManyPins: return "最多可以固定 20 条记录。"
        case .unsupportedVersion: return "历史文件来自更新版本，已停止记录以保护原文件。"
        case .invalidImage: return "图片数据不完整或尺寸过大。"
        case .invalidFormats: return "富文本格式不受支持或数据已损坏。"
        case .invalidFileReferences: return "文件引用无效，仅支持本机文件和文件夹。"
        case .damagedHistory: return "历史文件无法读取，已停止记录以保护原文件。"
        case .manifestTooLarge: return "历史索引超过安全大小限制，无法读取或保存；现有记录未被覆盖。"
        case .excludedContent: return "已忽略被删除记录的过期采集。"
        case .capacityExceeded: return "历史容量不足，无法保存这条内容。请删除部分记录或取消固定后重试。"
        }
    }
}

public enum ClipboardPolicy {
    public static let ownType = "app.clipboarddeck.internal"
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "com.typeit4me.clipping", ownType,
    ]

    public static func shouldIgnore(types: [String]) -> Bool {
        !privateTypes.isDisjoint(with: types)
    }
}

/// A local, UI-independent history store. Sidecars and manifest are committed atomically;
/// obsolete sidecars are removed only after the new manifest is safely written.
public final class HistoryStore {
    private struct Document: Codable {
        let version: Int
        let entries: [ClipEntry]
    }
    private struct VersionHeader: Decodable { let version: Int }
    private struct RichTextDocument: Codable {
        let version: Int
        let formats: [String: Data]
    }

    public private(set) var entries: [ClipEntry] = []
    public let directory: URL
    public var maxItems: Int
    public let maxBytes: Int
    /// Serialized JSON budget, separate from original-content and process-memory budgets.
    /// 100 MiB of content can expand sixfold when JSON escapes control characters.
    public static let defaultMaxManifestBytes = 640 * 1_048_576
    public let maxManifestBytes: Int
    public static let maxTextBytes = 1_048_576
    public static let maxImageBytes = 20 * 1_048_576
    public static let maxImagePixels = 16_000_000
    public static let maxRichTextBytes = 4 * 1_048_576
    public static let maxFileCount = 100
    public static let maxFileReferenceBytes = 1_048_576
    public static let rtfdType = "com.apple.flat-rtfd"
    public static let richTextTypes: Set<String> = ["public.rtf", "public.html", rtfdType]
    private let manager = FileManager.default
    private var manifest: URL { directory.appendingPathComponent("history.json") }
    private var images: URL { directory.appendingPathComponent("images", isDirectory: true) }
    private var richText: URL { directory.appendingPathComponent("richtext", isDirectory: true) }

    /// `maxManifestBytes` may lower the default safety ceiling for a smaller store.
    public init(
        directory: URL, maxItems: Int = 200, maxBytes: Int = 100 * 1_048_576,
        maxManifestBytes: Int = HistoryStore.defaultMaxManifestBytes
    ) throws {
        self.directory = directory
        self.maxItems = max(1, maxItems)
        self.maxBytes = max(1, maxBytes)
        self.maxManifestBytes = min(Self.defaultMaxManifestBytes, max(1, maxManifestBytes))
        try manager.createDirectory(
            at: directory, withIntermediateDirectories: true,
            attributes: [.posixPermissions: 0o700])
        for url in [images, richText] {
            let existing = try? url.resourceValues(forKeys: [.isSymbolicLinkKey])
            guard existing?.isSymbolicLink != true else { throw HistoryError.damagedHistory }
            try manager.createDirectory(
                at: url, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try Self.requireSidecarDirectory(url)
        }
        if manager.fileExists(atPath: manifest.path) {
            let data = try readManifest()
            let header: VersionHeader
            do { header = try JSONDecoder().decode(VersionHeader.self, from: data) } catch {
                throw HistoryError.damagedHistory
            }
            // Decode the version first: a future version may introduce kinds
            // that this app cannot decode, but must never overwrite.
            guard (1...3).contains(header.version) else { throw HistoryError.unsupportedVersion }
            let doc: Document
            do { doc = try JSONDecoder().decode(Document.self, from: data) } catch { throw HistoryError.damagedHistory }
            guard doc.entries.allSatisfy({ Self.validMetadata($0, version: doc.version) }),
                Set(doc.entries.map(\.id)).count == doc.entries.count,
                Set(doc.entries.map(\.digest)).count == doc.entries.count
            else {
                throw HistoryError.damagedHistory
            }
            // Never interpret a manifest's image name as an arbitrary filesystem path.
            entries = doc.entries.filter { entry in
                if entry.kind == .text { return entry.text != nil }
                // Rich-text bytes are read and verified on demand, not loaded
                // for every history row. A missing sidecar remains detectable.
                if entry.kind == .richText || entry.kind == .files { return true }
                guard let name = entry.imageFilename, Self.validImageName(name) else { return false }
                return manager.fileExists(atPath: images.appendingPathComponent(name).path)
            }
        }
    }

    @discardableResult
    public func add(
        _ payload: ClipPayload, sourceApp: String, at date: Date = Date(), excludingDigests: Set<String> = []
    ) throws -> UUID {
        let data: Data
        let kind: ClipKind
        let text: String?
        let width: Int?
        let height: Int?
        var formats: [String: Data]?
        var fileReferences: [String]?
        var customDigest: String?
        let byteCount: Int
        switch payload {
        case .text(let string):
            guard !string.isEmpty else { throw HistoryError.emptyContent }
            data = Data(string.utf8)
            guard data.count <= Self.maxTextBytes else { throw HistoryError.tooLarge }
            kind = .text; text = string; width = nil; height = nil
            byteCount = data.count
        case .image(let png, let w, let h):
            guard w > 0, h > 0, w <= 20_000, h <= 20_000,
                Int64(w) * Int64(h) <= Int64(Self.maxImagePixels),
                png.starts(with: [137, 80, 78, 71, 13, 10, 26, 10])
            else {
                throw HistoryError.invalidImage
            }
            guard png.count <= Self.maxImageBytes else { throw HistoryError.tooLarge }
            data = png; kind = .image; text = nil; width = w; height = h
            byteCount = data.count
        case .richText(let string, let representations):
            let rawBytes = try Self.validateRichText(string, formats: representations)
            let encoder = PropertyListEncoder()
            encoder.outputFormat = .binary
            data = try encoder.encode(
                RichTextDocument(version: representations[Self.rtfdType] == nil ? 1 : 2, formats: representations))
            kind = .richText; text = string; width = nil; height = nil
            formats = representations
            byteCount = rawBytes + string.utf8.count
            customDigest = Self.richTextDigest(text: string, formats: representations)
        case .files(let urls):
            let references = try Self.fileReferences(urls)
            let names = references.compactMap { URL(string: $0)?.lastPathComponent }.joined(separator: "\n")
            kind = .files; text = names; width = nil; height = nil
            fileReferences = references
            data = Data()
            byteCount = references.reduce(0) { $0 + $1.utf8.count } + names.utf8.count
            customDigest = Self.framedDigest(kind: .files, parts: references.map { Data($0.utf8) })
        }
        // Preserve the existing prefix + payload digest without copying the
        // entire payload into a second buffer (images can be up to 20 MB).
        let digest: String
        if let customDigest {
            digest = customDigest
        } else {
            var hasher = SHA256()
            hasher.update(data: Data(kind.rawValue.utf8))
            hasher.update(data: data)
            digest = hasher.finalize().map { String(format: "%02x", $0) }.joined()
        }
        // Apply per-capture tombstones only after computing the canonical digest,
        // before recopy repair, sidecar writes or a new manifest can change disk.
        guard !excludingDigests.contains(digest) else { throw HistoryError.excludedContent }
        let name = kind == .image ? digest + ".png" : nil
        let richName = kind == .richText ? digest + ".plist" : nil
        var updated = entries
        if let index = updated.firstIndex(where: { $0.digest == digest }) {
            let previous = updated.remove(at: index)
            // A fresh validated payload is authoritative for derived metadata.
            // Repairing only sidecar bytes would leave a damaged size, dimension
            // or format summary permanently unusable even after a valid recopy.
            let existing = ClipEntry(
                id: previous.id, digest: digest, kind: kind, text: text,
                imageFilename: name, imageWidth: width, imageHeight: height,
                richTextFilename: richName, richTextTypes: formats?.keys.sorted(), fileURLs: fileReferences,
                byteCount: byteCount, createdAt: previous.createdAt, copiedAt: date,
                sourceApp: sourceApp, isPinned: previous.isPinned,
                copyCount: previous.copyCount < Int.max ? previous.copyCount + 1 : Int.max)
            updated.insert(existing, at: 0)
            let retained = trimmed(updated)
            guard retained.contains(where: { $0.id == existing.id }) else {
                throw HistoryError.capacityExceeded
            }
            // The file may have been removed or corrupted while the app was
            // running. A fresh copy repairs bytes without replacing the entry.
            if kind == .image, let url = imageURL(for: existing),
                !imageMatches(data, at: url)
            {
                try writeSidecar(data, to: url)
            }
            if kind == .richText, let name = existing.richTextFilename {
                // Repair missing or damaged bytes from a fresh valid copy.
                // No original file referenced by a .files entry is touched.
                if (try? richTextFormats(for: existing)) == nil {
                    try writeSidecar(data, to: richText.appendingPathComponent(name))
                }
            }
            try commit(retained)
            return existing.id
        }
        let entry = ClipEntry(
            id: UUID(), digest: digest, kind: kind, text: text,
            imageFilename: name, imageWidth: width, imageHeight: height,
            richTextFilename: richName, richTextTypes: formats?.keys.sorted(), fileURLs: fileReferences,
            byteCount: byteCount, createdAt: date, copiedAt: date,
            sourceApp: sourceApp, isPinned: false, copyCount: 1)
        updated.insert(entry, at: 0)
        let retained = trimmed(updated)
        // A pinned history can leave no room for the new item. Reject the capture
        // before writing anything, rather than silently evicting the new item and
        // any older unpinned records while returning success.
        guard retained.contains(where: { $0.id == entry.id }) else {
            throw HistoryError.capacityExceeded
        }
        if let name {
            let url = images.appendingPathComponent(name)
            try writeSidecar(data, to: url)
        }
        if let richName { try writeSidecar(data, to: richText.appendingPathComponent(richName)) }
        try commit(retained)
        return entry.id
    }

    public func togglePin(_ id: UUID) throws {
        var updated = entries
        guard let index = updated.firstIndex(where: { $0.id == id }) else { return }
        if !updated[index].isPinned && updated.filter(\.isPinned).count >= 20 {
            throw HistoryError.tooManyPins
        }
        updated[index].isPinned.toggle()
        try commit(trimmed(updated))
    }

    public func remove(_ id: UUID) throws {
        let updated = entries.filter { $0.id != id }
        guard updated.count != entries.count else {
            cleanupUnusedSidecars(entries)
            return
        }
        try commit(updated)
    }
    public func clear(keepingPinned: Bool = true) throws {
        let updated = keepingPinned ? entries.filter(\.isPinned) : []
        guard updated.count != entries.count else {
            cleanupUnusedSidecars(entries)
            return
        }
        try commit(updated)
    }
    public func applyLimit(_ limit: Int) throws {
        let previous = maxItems
        maxItems = max(1, limit)
        let updated = trimmed(entries)
        // Limits are settings, not part of the manifest. A change that removes
        // no entries needs no disk write, but still applies to future captures.
        guard updated.count != entries.count else {
            cleanupUnusedSidecars(entries)
            return
        }
        do { try commit(updated) } catch { maxItems = previous; throw error }
    }

    public func matching(_ query: String, kind: ClipKind? = nil) -> [ClipEntry] {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines)
        return entries.filter { entry in
            (kind == nil || entry.kind == kind)
                && (q.isEmpty || entry.title.localizedCaseInsensitiveContains(q)
                    || entry.sourceApp.localizedCaseInsensitiveContains(q))
        }.sorted {
            if $0.isPinned != $1.isPinned { return $0.isPinned }
            return $0.copiedAt > $1.copiedAt
        }
    }

    public func imageURL(for entry: ClipEntry) -> URL? {
        guard let name = entry.imageFilename, Self.validImageName(name) else { return nil }
        return images.appendingPathComponent(name)
    }

    /// Return exact persisted bytes only when needed for a copy / paste.
    /// The manifest contains small metadata and a plain-text fallback only.
    public func richTextFormats(for entry: ClipEntry) throws -> [String: Data] {
        try Self.richTextFormats(for: entry, directory: directory)
    }

    /// Read one immutable entry without sharing a mutable HistoryStore across queues.
    public static func richTextFormats(for entry: ClipEntry, directory: URL) throws -> [String: Data] {
        let richText = directory.appendingPathComponent("richtext", isDirectory: true)
        guard entry.kind == .richText,
            let name = entry.richTextFilename, Self.validRichTextName(name),
            name == entry.digest + ".plist", let text = entry.text
        else {
            throw HistoryError.invalidFormats
        }
        let url = richText.appendingPathComponent(name)
        do {
            let parent = try richText.resourceValues(forKeys: [.isDirectoryKey, .isSymbolicLinkKey])
            let info = try url.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey])
            guard parent.isDirectory == true, parent.isSymbolicLink != true,
                info.isRegularFile == true, info.isSymbolicLink != true,
                let size = info.fileSize, size > 0, size <= Self.maxRichTextBytes + 65_536
            else {
                throw HistoryError.invalidFormats
            }
            let handle = try FileHandle(forReadingFrom: url)
            defer { try? handle.close() }
            let limit = Self.maxRichTextBytes + 65_536
            let bytes = try BoundedFileReader.read(from: handle, limit: limit + 1)
            guard bytes.count <= limit else {
                throw HistoryError.invalidFormats
            }
            let document = try PropertyListDecoder().decode(RichTextDocument.self, from: bytes)
            guard document.version == (document.formats[Self.rtfdType] == nil ? 1 : 2) else {
                throw HistoryError.invalidFormats
            }
            let count = try Self.validateRichText(text, formats: document.formats)
            guard document.formats.keys.sorted() == entry.richTextTypes,
                count + text.utf8.count == entry.byteCount,
                Self.richTextDigest(text: text, formats: document.formats) == entry.digest
            else {
                throw HistoryError.invalidFormats
            }
            return document.formats
        } catch { throw HistoryError.invalidFormats }
    }

    private func writeSidecar(_ data: Data, to url: URL) throws {
        try Self.requireSidecarDirectory(url.deletingLastPathComponent())
        try data.write(to: url, options: .atomic)
        try manager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }

    private static func requireSidecarDirectory(_ url: URL) throws {
        let info = try url.resourceValues(forKeys: [.isDirectoryKey, .isSymbolicLinkKey])
        guard info.isDirectory == true, info.isSymbolicLink != true else { throw HistoryError.damagedHistory }
    }

    private func readManifest() throws -> Data {
        let info = try manifest.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey])
        guard info.isRegularFile == true, info.isSymbolicLink != true else { throw HistoryError.damagedHistory }
        guard let size = info.fileSize, size <= maxManifestBytes else { throw HistoryError.manifestTooLarge }
        let handle = try FileHandle(forReadingFrom: manifest)
        defer { try? handle.close() }
        var status = stat()
        guard fstat(handle.fileDescriptor, &status) == 0, (status.st_mode & S_IFMT) == S_IFREG else {
            throw HistoryError.damagedHistory
        }
        guard status.st_size <= Int64(maxManifestBytes) else { throw HistoryError.manifestTooLarge }
        let data = try BoundedFileReader.read(from: handle, limit: maxManifestBytes + 1)
        guard data.count <= maxManifestBytes else { throw HistoryError.manifestTooLarge }
        return data
    }

    /// Detect corruption on a fresh copy without allocating another full PNG buffer.
    private func imageMatches(_ data: Data, at url: URL) -> Bool {
        do {
            try Self.requireSidecarDirectory(images)
            let info = try url.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey])
            guard info.isRegularFile == true, info.isSymbolicLink != true, info.fileSize == data.count else {
                return false
            }
            let handle = try FileHandle(forReadingFrom: url)
            defer { try? handle.close() }
            var offset = 0
            while offset < data.count {
                let end = min(offset + 65_536, data.count)
                let bytes = try BoundedFileReader.read(from: handle, limit: end - offset)
                guard bytes == data[offset..<end] else { return false }
                offset = end
            }
            return try BoundedFileReader.read(from: handle, limit: 1).isEmpty
        } catch { return false }
    }

    private static func validateRichText(_ text: String, formats: [String: Data]) throws -> Int {
        guard !formats.isEmpty, Set(formats.keys).isSubset(of: richTextTypes),
            formats.values.allSatisfy({ !$0.isEmpty })
        else { throw HistoryError.invalidFormats }
        guard text.utf8.count <= maxTextBytes else { throw HistoryError.tooLarge }
        var count = 0
        for data in formats.values {
            guard data.count <= maxRichTextBytes - count else { throw HistoryError.tooLarge }
            count += data.count
        }
        return count
    }

    private static func fileReferences(_ urls: [URL]) throws -> [String] {
        guard !urls.isEmpty else { throw HistoryError.emptyContent }
        guard urls.count <= maxFileCount else { throw HistoryError.tooLarge }
        var result: [String] = []
        var seen: Set<String> = []
        var bytes = 0
        for url in urls {
            // Bound the supplied representation before Foundation normalizes it.
            guard url.absoluteString.utf8.count <= maxFileReferenceBytes else { throw HistoryError.tooLarge }
            guard url.isFileURL, url.path.hasPrefix("/"), !url.path.contains("\0"),
                url.host == nil || url.host == "" || url.host?.lowercased() == "localhost",
                url.user == nil, url.password == nil, url.port == nil,
                url.query == nil, url.fragment == nil
            else { throw HistoryError.invalidFileReferences }
            let reference = url.standardizedFileURL.absoluteString
            guard seen.insert(reference).inserted else { continue }
            guard reference.utf8.count <= maxFileReferenceBytes - bytes else { throw HistoryError.tooLarge }
            bytes += reference.utf8.count
            result.append(reference)
        }
        return result
    }

    private static func richTextDigest(text: String, formats: [String: Data]) -> String {
        var parts = [Data(text.utf8)]
        for type in formats.keys.sorted() {
            parts.append(Data(type.utf8))
            parts.append(formats[type]!)
        }
        return framedDigest(kind: .richText, parts: parts)
    }

    /// Length framing keeps boundaries unambiguous without building another
    /// multi-megabyte buffer. Legacy text / PNG digests stay unchanged.
    private static func framedDigest(kind: ClipKind, parts: [Data]) -> String {
        var hasher = SHA256()
        hasher.update(data: Data(kind.rawValue.utf8))
        for part in parts {
            var length = UInt64(part.count).bigEndian
            withUnsafeBytes(of: &length) { hasher.update(data: Data($0)) }
            hasher.update(data: part)
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    private static func validMetadata(_ entry: ClipEntry, version: Int) -> Bool {
        guard entry.byteCount > 0, entry.copyCount > 0,
            entry.digest.range(of: "^[a-f0-9]{64}$", options: .regularExpression) != nil
        else { return false }
        if version == 1 && entry.kind != .text && entry.kind != .image { return false }
        switch entry.kind {
        case .text:
            guard let text = entry.text, !text.isEmpty, text.utf8.count <= maxTextBytes,
                entry.byteCount == text.utf8.count
            else { return false }
            var hasher = SHA256()
            hasher.update(data: Data(ClipKind.text.rawValue.utf8))
            hasher.update(data: Data(text.utf8))
            return hasher.finalize().map { String(format: "%02x", $0) }.joined() == entry.digest
        case .image:
            guard let name = entry.imageFilename, validImageName(name), name == entry.digest + ".png",
                let width = entry.imageWidth, let height = entry.imageHeight,
                width > 0, height > 0, width <= 20_000, height <= 20_000,
                Int64(width) * Int64(height) <= 40_000_000
            else { return false }
            return entry.byteCount >= 8 && entry.byteCount <= maxImageBytes
        case .richText:
            guard let name = entry.richTextFilename, validRichTextName(name), name == entry.digest + ".plist",
                let types = entry.richTextTypes, !types.isEmpty, types == Array(Set(types)).sorted(),
                Set(types).isSubset(of: richTextTypes),
                (version >= 3 || !types.contains(rtfdType)), let text = entry.text,
                text.utf8.count <= maxTextBytes, entry.byteCount <= maxRichTextBytes + maxTextBytes
            else { return false }
            return true
        case .files:
            guard let references = entry.fileURLs, references.count <= maxFileCount else { return false }
            let urls = references.compactMap(URL.init(string:))
            guard urls.count == references.count, let normalized = try? fileReferences(urls),
                normalized == references
            else { return false }
            let names = urls.map(\.lastPathComponent).joined(separator: "\n")
            return entry.text == names
                && entry.byteCount == references.reduce(0, { $0 + $1.utf8.count }) + names.utf8.count
                && framedDigest(kind: .files, parts: references.map { Data($0.utf8) }) == entry.digest
        }
    }

    private func trimmed(_ input: [ClipEntry]) -> [ClipEntry] {
        var result = input
        var bytes = result.reduce(0) { $0 + $1.byteCount }
        while result.count > maxItems || bytes > maxBytes {
            guard let index = result.lastIndex(where: { !$0.isPinned }) else { break }
            bytes -= result[index].byteCount
            result.remove(at: index)
        }
        return result
    }

    private func commit(_ updated: [ClipEntry]) throws {
        // Source app names are externally supplied strings. Reject an impossible
        // serialized size before JSON encoding allocates another copy.
        var remaining = maxManifestBytes
        for entry in updated {
            let bytes = entry.sourceApp.utf8.count
            guard bytes <= remaining else { throw HistoryError.manifestTooLarge }
            remaining -= bytes
        }
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        // A v2 reader must stop before touching history that contains RTFD.
        // Histories without the new representation remain backward compatible.
        let version = updated.contains { $0.richTextTypes?.contains(Self.rtfdType) == true } ? 3 : 2
        let data = try encoder.encode(Document(version: version, entries: updated))
        guard data.count <= maxManifestBytes else { throw HistoryError.manifestTooLarge }
        try data.write(to: manifest, options: .atomic)
        try manager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: manifest.path)
        entries = updated
        cleanupUnusedSidecars(updated)
    }

    private func cleanupUnusedSidecars(_ retained: [ClipEntry]) {
        // Preserve orphan recovery after a failed image capture even when the
        // next remove/clear/limit operation does not need a manifest write.
        let used = Set(retained.compactMap(\.imageFilename))
        if (try? Self.requireSidecarDirectory(images)) != nil {
            for url in (try? manager.contentsOfDirectory(at: images, includingPropertiesForKeys: nil)) ?? [] {
                if Self.validImageName(url.lastPathComponent) && !used.contains(url.lastPathComponent) {
                    try? manager.removeItem(at: url)
                }
            }
        }
        let usedRichText = Set(retained.compactMap(\.richTextFilename))
        // Only app-owned digest names are eligible. Never walk fileURLs or
        // follow a replaced sidecar directory into an unrelated location.
        let richInfo = try? richText.resourceValues(forKeys: [.isDirectoryKey, .isSymbolicLinkKey])
        guard richInfo?.isDirectory == true, richInfo?.isSymbolicLink != true else { return }
        for url in (try? manager.contentsOfDirectory(at: richText, includingPropertiesForKeys: nil)) ?? [] {
            if Self.validRichTextName(url.lastPathComponent) && !usedRichText.contains(url.lastPathComponent) {
                try? manager.removeItem(at: url)
            }
        }
    }

    private static func validImageName(_ value: String) -> Bool {
        value.range(of: "^[a-f0-9]{64}\\.png$", options: .regularExpression) != nil
    }
    private static func validRichTextName(_ value: String) -> Bool {
        value.range(of: "^[a-f0-9]{64}\\.plist$", options: .regularExpression) != nil
    }
}
